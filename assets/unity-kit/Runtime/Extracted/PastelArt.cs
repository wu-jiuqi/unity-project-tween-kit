 static void Load(){if(data!=null)return;data=new Dictionary<string,Item>();sprites=new Dictionary<string,Sprite>();var file=Resources.Load<TextAsset>("Art/Pastel/PastelArtData");if(file==null)throw new Exception("PastelArtData missing");foreach(var item in JsonUtility.FromJson<Data>(file.text).sprites)data.Add(item.name,item);}
 public static int Count{get{Load();return data.Count;}}
 public static Sprite Get(string name){Load();if(sprites.TryGetValue(name,out var s))return s;if(!data.TryGetValue(name,out var item))return null;s=Resources.Load<Sprite>(item.resource);if(s==null)throw new Exception("Pastel sprite missing: "+item.resource);sprites.Add(name,s);return s;}
 public static Item Info(string name){Load();return data.TryGetValue(name,out var i)?i:null;}
 public static Sprite Resolve(string key){if(key.StartsWith("pastel/"))return Get(key.Substring(7));return aliases.TryGetValue(key,out var name)?Get(name):null;}
 public static Rect FootprintLocal(Sprite sprite){var i=Info(sprite.name);var r=i.footprint;float sx=sprite.rect.width/i.size[0],sy=sprite.rect.height/i.size[1],ppu=sprite.pixelsPerUnit;return new Rect((r[0]*sx-sprite.pivot.x)/ppu,((i.size[1]-r[1]-r[3])*sy-sprite.pivot.y)/ppu,r[2]*sx/ppu,r[3]*sy/ppu);}
 public static void FitCell(SpriteRenderer face,float width,float height){var r=FootprintLocal(face.sprite);face.transform.localScale=new Vector3(width/r.width,height/r.height,1);face.transform.localPosition=new Vector3(-r.center.x*width/r.width,-r.center.y*height/r.height,0);}
 public static void FitVisible(SpriteRenderer face,Vector2 center,Vector2 size){var i=Info(face.sprite.name);if(i==null)return;var r=i.visible;var sprite=face.sprite;float ax=sprite.rect.width/i.size[0],ay=sprite.rect.height/i.size[1],ppu=sprite.pixelsPerUnit;float sx=size.x*ppu/(r[2]*ax),sy=size.y*ppu/(r[3]*ay);face.transform.localScale=new Vector3(sx,sy,1);var c=new Vector2((r[0]+r[2]*.5f)*ax-sprite.pivot.x,(i.size[1]-r[1]-r[3]*.5f)*ay-sprite.pivot.y)/ppu;face.transform.localPosition=center-new Vector2(c.x*sx,c.y*sy);}

